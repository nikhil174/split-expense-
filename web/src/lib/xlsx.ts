// A small Excel (.xlsx) writer: an .xlsx file is a zip of XML parts. Enough
// for statements: several sheets, text and numbers, bold headers, a title
// style, ₹ amounts, column widths and a frozen header row.
import { strToU8, zipSync } from "fflate";

export type Style = "bold" | "money" | "boldMoney" | "title" | "muted" | "header";
export type Cell = string | number | null | undefined | { v: string | number; s?: Style };
export type Sheet = { name: string; widths?: number[]; rows: Cell[][]; freezeRow?: number };

// Style ids in styles.xml (cellXfs order below).
const STYLE_ID: Record<Style, number> = { bold: 1, money: 2, boldMoney: 3, title: 4, muted: 5, header: 6 };
const esc = (s: string) => s.replace(/[&<>"]/g, c => ({ "&": "&amp;", "<": "&lt;", ">": "&gt;", '"': "&quot;" })[c]!).replace(/[\u0000-\u0008\u000b\u000c\u000e-\u001f]/g, "");
const col = (i: number) => { let s = ""; for (i++; i > 0; i = Math.floor((i - 1) / 26)) s = String.fromCharCode(65 + ((i - 1) % 26)) + s; return s; };

// Excel sheet names: at most 31 characters, none of []:*?/\ , unique.
export function sheetNames(names: string[]) {
  const used = new Set<string>();
  return names.map(n => {
    const base = (n.replace(/[[\]:*?/\\]/g, " ").trim() || "Sheet").slice(0, 31);
    let name = base, k = 2;
    while (used.has(name.toLowerCase())) { const suffix = ` (${k++})`; name = base.slice(0, 31 - suffix.length) + suffix; }
    used.add(name.toLowerCase());
    return name;
  });
}

function sheetXml(sheet: Sheet) {
  const rows = sheet.rows.map((cells, r) => {
    const xml = cells.map((cell, c) => {
      if (cell === null || cell === undefined || cell === "") return "";
      const { v, s } = typeof cell === "object" ? cell : { v: cell, s: undefined };
      const ref = col(c) + (r + 1), st = s ? ` s="${STYLE_ID[s]}"` : "";
      return typeof v === "number"
        ? `<c r="${ref}"${st}><v>${Number.isFinite(v) ? v : 0}</v></c>`
        : `<c r="${ref}"${st} t="inlineStr"><is><t xml:space="preserve">${esc(String(v))}</t></is></c>`;
    }).join("");
    return `<row r="${r + 1}">${xml}</row>`;
  }).join("");
  const cols = sheet.widths?.length ? `<cols>${sheet.widths.map((w, i) => `<col min="${i + 1}" max="${i + 1}" width="${w}" customWidth="1"/>`).join("")}</cols>` : "";
  const freeze = sheet.freezeRow ? `<sheetViews><sheetView workbookViewId="0"><pane ySplit="${sheet.freezeRow}" topLeftCell="A${sheet.freezeRow + 1}" activePane="bottomLeft" state="frozen"/></sheetView></sheetViews>` : "";
  return `<?xml version="1.0" encoding="UTF-8" standalone="yes"?><worksheet xmlns="http://schemas.openxmlformats.org/spreadsheetml/2006/main">${freeze}${cols}<sheetData>${rows}</sheetData></worksheet>`;
}

